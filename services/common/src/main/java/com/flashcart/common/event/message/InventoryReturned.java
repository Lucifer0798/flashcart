package com.flashcart.common.event.message;

import java.time.Instant;

import com.flashcart.common.event.DomainEvent;
import com.flashcart.common.event.EventMetadata;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;

/** Units that had been sold are back in circulation, because the sale was undone. */
@JsonIgnoreProperties(ignoreUnknown = true)
public record InventoryReturned(EventMetadata metadata,
		String reservationKey,
		String reason) implements DomainEvent {

	public static final String TYPE = "InventoryReturned";


	@Override
	public String eventId() {
		return metadata.eventId();
	}

	@Override
	public String eventType() {
		return metadata.eventType();
	}

	@Override
	public String aggregateId() {
		return metadata.aggregateId();
	}

	@Override
	public Instant occurredAt() {
		return metadata.occurredAt();
	}

	@Override
	public String correlationId() {
		return metadata.correlationId();
	}
}
